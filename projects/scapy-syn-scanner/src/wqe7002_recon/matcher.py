"""Response matching and classification.

Only replies that (a) are addressed to the scanner's own interface and
(b) correspond byte-for-byte to one of the recorded probes are classified.
Everything else is ignored as unrelated.  TCP replies must additionally come
from the authorised target; ICMP unreachables are normally generated by an
intermediate router rather than the target, so their relevance is proven by
their quoted original segment instead of by their source address.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

from scapy.all import Ether, ICMP, IP, TCP  # type: ignore
from scapy.packet import Packet  # type: ignore

from .scope import RELEVANT_UNREACHABLE_CODES

SYN_ACK_KIND = "syn-ack"
RST_KIND = "rst"
ICMP_KIND = "icmp-unreachable"


@dataclass(frozen=True)
class ProbeRecord:
    """Bookkeeping for one transmitted probe."""

    port: int
    source_port: int
    sequence: int
    attempt: int


# sport -> {attempt -> ProbeRecord}
Registry = dict[int, dict[int, ProbeRecord]]


@dataclass(frozen=True)
class Match:
    """A verified reply mapped to the probe it answers."""

    probe: ProbeRecord
    kind: str
    icmp_code: Optional[int] = None
    syn_ack_seq: Optional[int] = None
    syn_ack_ack: Optional[int] = None


def _find_by_ack(
    records: dict[int, ProbeRecord], ack: int
) -> Optional[ProbeRecord]:
    for record in records.values():
        if record.sequence + 1 == ack:
            return record
    return None


def _find_by_seq(
    records: dict[int, ProbeRecord], seq: int
) -> Optional[ProbeRecord]:
    for record in records.values():
        if record.sequence == seq:
            return record
    return None


def match_own_probe(
    packet: Packet,
    registry: Registry,
    target_ip: str,
    our_ip: str,
    our_mac: str,
) -> Optional[ProbeRecord]:
    """Identify one of our own outbound SYN probes in the capture.

    The scanner records its own probes' wire timestamps so that every RTT is
    computed from one clock (the capture's) instead of mixing the Python
    clock with libpcap timestamps, which skew on virtualised hosts.
    """
    ether = packet.getlayer(Ether)
    if ether is None or ether.src != our_mac:
        return None
    ip = packet.getlayer(IP)
    if ip is None or ip.src != our_ip or ip.dst != target_ip:
        return None
    tcp = packet.getlayer(TCP)
    if tcp is None or int(tcp.flags) & 0x02 == 0:
        return None  # not a SYN we sent
    records = registry.get(int(tcp.sport))
    if not records:
        return None
    record = _find_by_seq(records, int(tcp.seq))
    if record is None or int(tcp.dport) != record.port:
        return None
    return record


def match_reply(
    packet: Packet,
    registry: Registry,
    target_ip: str,
    our_ip: str,
    our_mac: str,
) -> Optional[Match]:
    """Classify one captured frame, or return ``None`` when unrelated.

    ``packet`` is an Ethernet frame as sniffed on the scanning interface.
    """
    ether = packet.getlayer(Ether)
    if ether is None or ether.src == our_mac or ether.dst != our_mac:
        return None  # not inbound to this interface
    ip = packet.getlayer(IP)
    if ip is None or ip.dst != our_ip:
        return None  # not addressed to the scanner's own interface

    # --- ICMP replies first: an ICMP error may quote a TCP segment, which
    # must never be mistaken for the outer transport layer -----------------
    icmp = packet.getlayer(ICMP)
    if icmp is not None:
        if int(icmp.type) != 3:
            return None  # echo, redirect, etc.; not a scan response
        code = int(icmp.code)
        if code not in RELEVANT_UNREACHABLE_CODES:
            return None
        quoted = icmp.payload
        quoted_ip = quoted.getlayer(IP)
        quoted_tcp = quoted.getlayer(TCP) if quoted_ip is not None else None
        if quoted_ip is None or quoted_tcp is None:
            return None  # unreachable without a verifiable quoted segment
        if quoted_ip.dst != target_ip:
            return None  # the quoted packet was not one of ours
        records = registry.get(int(quoted_tcp.sport))
        if not records:
            return None  # quoted TCP does not match any probe
        record = _find_by_seq(records, int(quoted_tcp.seq))
        if record is None:
            return None
        return Match(probe=record, kind=ICMP_KIND, icmp_code=code)

    # --- TCP replies ------------------------------------------------------
    if ip.src != target_ip:
        return None  # TCP must come from the authorised target
    tcp = packet.getlayer(TCP)
    if tcp is not None:
        # A reply's destination port is the source port *we* chose for the
        # probe, which is exactly how the registry is keyed.
        records = registry.get(int(tcp.dport))
        if not records:
            return None  # TCP from the target but not for any probe
        flags = int(tcp.flags)
        if flags & 0x12 == 0x12:  # SYN + ACK
            record = _find_by_ack(records, int(tcp.ack))
            if record is None:
                return None  # wrong acknowledgement number: unrelated flow
            return Match(
                probe=record,
                kind=SYN_ACK_KIND,
                syn_ack_seq=int(tcp.seq),
                syn_ack_ack=int(tcp.ack),
            )
        if flags & 0x04 and not flags & 0x02:  # RST without SYN
            record = _find_by_ack(records, int(tcp.ack))
            if record is None:
                # Some stacks reset with ack=0; attribute to the most recent
                # probe for that source port.
                record = records[max(records)]
            return Match(probe=record, kind=RST_KIND)
        return None  # FIN/PSH/ACK or other: not a scan response

    return None
